    public void CalculateEH(){
        
        Date comecou = new Date();
        
        for (int n=0; n<max; n++){
            if(stopThread)
                return;
            System.out.println(" *** N  = "+n+" de "+max);
            setBar(n+1);
            int TX = C[0].SizeX(); int TY = C[0].SizeY(); int TZ = C[0].SizeZ();
            
            try {
                // Enroll in the parallel virtual machine...
                jpvmEnvironment jpvm = new jpvmEnvironment();
                
                jpvmTaskId mytid = jpvm.pvm_mytid();
                jpvmTaskId tids[] = new jpvmTaskId[NPROC];
                //System.out.println("*** CalculateEHFrame::CalculateEHJPVM()::Slave tasks: ");
                jpvm.pvm_spawn("FDTD_slave",NPROC,tids);
                
                //for(int i=0;i<NPROC;i++) System.out.println("     TASK "+i+" = "+tids[i].toString());
                
                int numData = (TX-1)/NPROC;
                if((TX-1)%NPROC!=0){
                    System.out.println("*** PARALELIZACAO NO X NAO E' POSSIVEL!");
                    System.out.println("*** TX = "+TX+"  NPROC = "+NPROC);
                    System.exit(0);
                }
                int Xi=0, Yi=0, Zi=0;
                int Xf=Xi+numData, Yf=TY, Zf=TZ;
                
                for (int i=0;i<NPROC; i++) {
                    //PVM:
                    jpvmMessage message = jpvm.pvm_recv();
                    String str = message.buffer.upkstr();
                    
                    double[][][] init = new double[numData][TY][TZ];
                    int xx=0;
                    for (int x=Xi; x<Xf; x++)
                        for (int y=0; y<TY; y++)
                            for (int z=0; z<TZ; z++){
                        init[xx][y][z] = C[0].data(x,y,z);
                            }
                    //sendCase(i, tids, init, TX, TY, TZ, jpvm);
                    
                    //So na bota:
                    System.out.println("** Fazendo de "+Xi+" a "+Xf+" em X");
                    FDTDParallelProcess(TX, TY, TZ, Xi, Xf, Yi, Yf, Zi, Zf, n);
                    Xi+=numData; Xf+=numData;
                }
                
            /* Refresh GERAL -> foi substituido pelo LOCAL
             Field.Refresh(C);
             */
                
                if (n%skip==0){
                    C[0].Save(PATH,SimulName,n,this);
                }
                
                //System.out.println("*** CalculateEHFrame::CalculateEHJPVM():: COMMUNICATION OK!");
                jpvm.pvm_exit();
                
            } catch (jpvmException jpe) {
                String texto = new String("*** CalculateEHFrame::CalculateEH()::Error - jpvm exception"+jpe.toString());
                System.out.println(texto);
                System.out.println(jpe.toString());
                JOptionPane.showMessageDialog(this,texto,"ERRO NO CALCULO",JOptionPane.ERROR_MESSAGE);
        
            }
        }
        
        Date terminou = new Date();
        long tempoTotal = (terminou.getTime()-comecou.getTime());
        System.out.println("*** Tempo de simulacao = "+(tempoTotal/1000.0)+" segundos");
        String texto = new String("Fim da Simulacao!! Tempo = "+(tempoTotal/1000.0)+"s.");
        JOptionPane.showMessageDialog(this,texto,"End of Simulation",JOptionPane.INFORMATION_MESSAGE);
        EHCalculated = true;
        this.setVisible(false);
        
        
    }
    
