    void setNodes(DefaultMutableTreeNode pai, String[] filhos){
        DefaultMutableTreeNode filho;
        int NumFilhos = filhos.length;
        for (int i=0; i<NumFilhos; i++){
            filho = new DefaultMutableTreeNode(filhos[i]);
            pai.add(filho);
        }
    }
    
    
