    private void ReadTinitFile(File IF) {
        String filename = IF.getAbsolutePath();
        System.out.println("*** CalculateTFrameParallel::ReadTinitFile():: Arquivo " + filename);

        // Reads the data.
        if (filename == null) {
            throw new RuntimeException("ModelLoader.NoFileNameError");
        }
        String basefile = (filename);
        try {
            //System.out.println("*** Arquivo de dados = "+basefile);

            LineNumberReader r;
            try {
                r = new LineNumberReader(new InputStreamReader(new FileInputStream(basefile)));
            } catch (Exception e) {
                throw new RuntimeException(e.toString());
            }

            String token;
            try {
                for (int i = 0; i < gridSizeX; i++) {
                    for (int j = 0; j < gridSizeY; j++) {
                        for (int k = 0; k < gridSizeZ; k++) {
                            token = getNextToken(r);
                            if (token == null) {
                                throw new RuntimeException("TinitLoader.PrematureEOF");
                            }
                            try {
                                double v = Double.valueOf(token).doubleValue();
                                Tinit.data(i, j, k, v);

                            } catch (NumberFormatException e) {
                                e.printStackTrace();
                                throw new RuntimeException(e);
                            }
                        }
                    }
                }


            } catch (java.net.MalformedURLException e) {
                throw new RuntimeException(e.toString());
            }

        } catch (IOException e) {
            throw new RuntimeException(e.toString());
        }

    }

    private String getNextToken(Reader r) throws IOException {
        StringBuffer token = new StringBuffer();
        char c;
        int val;
        do {
            val = r.read();
            c = (char) val;
        } while (val != -1 && Character.isWhitespace(c));

        if (val == -1) {
            return null;
        }
        while (val != -1 && !Character.isWhitespace(c)) {

            token.append(c);
            val = r.read();
            c = (char) val;
        }

        return token.toString();
    }

